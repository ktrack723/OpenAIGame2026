// 쌓인다. 그래서 어떤 보이스든 onended에서 disconnect한다 — 이 파일에서
// 노드를 만드는 자리는 셋뿐이고(buffer/osc/noise) 셋 다 같은 규율을 따른다.
//
// ── 같은 소리가 겹치면 ──
// 행성 충돌은 한 번의 접촉에서 여러 스텝 붙어 있고, 폭풍 하나가 공 여섯 개를
// 동시에 민다. 그대로 내면 같은 파형이 위상만 어긋난 채 겹쳐 "플랜징"이 걸리고
