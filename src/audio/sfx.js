export class Sfx {
  constructor(engine) {
    this.engine = engine
    this.buffers = new Map()     // key → AudioBuffer
    this.last = new Map()        // key → 마지막 재생 시각(컨텍스트 초)
    this.voices = 0
    this.noiseBuf = null
  }

  get ctx() { return this.engine.ctx }

  // ── 굽기 ──
  // 개막에 전 뱅크를 한 번 돈다. 한 덩어리로 돌리면 그동안 화면이 멈추므로
  // 몇 개씩 끊어 가며 굽는다. 다 굽기 전에 재생 요청이 오면 그 자리에서
  // 하나만 먼저 굽는다(ensure) — 첫 소리가 안 나는 것보다 낫다.
  async prerender(chunk = 6) {
    if (!this.ctx) return
    const keys = Object.keys(BANK)
    for (let i = 0; i < keys.length; i++) {
      this.ensure(keys[i])
      if (i % chunk === chunk - 1) await new Promise(r => setTimeout(r, 0))
    }
    this.ensureNoise()
  }

  // 한 소리를 굽는다. 겹이 여럿이면 오프셋만큼 밀어 한 버퍼에 합친다 —
  // 재생할 때 노드가 하나면 되므로 겹이 몇 장이든 비용이 같다.
  ensure(key) {
    if (!this.ctx || this.buffers.has(key)) return this.buffers.get(key)
    const layers = BANK[key]
    if (!layers) return null
    const rendered = layers.map(l => ({ s: zzfxSamples(...l.p), off: Math.round((l.at || 0) * ZZFX_RATE) }))
    let n = 0
    for (const r of rendered) n = Math.max(n, r.off + r.s.length)
    const buf = this.ctx.createBuffer(1, Math.max(1, n), ZZFX_RATE)
    const out = buf.getChannelData(0)
    for (const r of rendered) {
      for (let i = 0; i < r.s.length; i++) out[r.off + i] += r.s[i]
    }
    // 믹스 — 이 소리의 자리(MIX)까지 통째로 키우거나 줄인다.
    // **클립하지 않고 비율로** 민다. 여기서 잘라내면 파형이 각져서
    // "지직"이 버퍼에 구워지고, 그건 재생할 때 아무리 줄여도 안 없어진다.
    let peak = 0
    for (let i = 0; i < out.length; i++) { const a = out[i] < 0 ? -out[i] : out[i]; if (a > peak) peak = a }
    if (peak > 1e-6) {
      const k = (MIX[key] ?? MIX_DEFAULT) / peak
      for (let i = 0; i < out.length; i++) out[i] *= k
    }
    this.buffers.set(key, buf)
    return buf
  }

  // 화이트 노이즈 한 초. 치지직·분사처럼 "길이를 그때그때 정하는" 소리가 쓴다.
  ensureNoise() {
    if (this.noiseBuf || !this.ctx) return this.noiseBuf
    const n = ZZFX_RATE
    const buf = this.ctx.createBuffer(1, n, ZZFX_RATE)
    const d = buf.getChannelData(0)
    for (let i = 0; i < n; i++) d[i] = Math.random() * 2 - 1
    this.noiseBuf = buf
    return buf
  }

  // ── 재생 ──
  // gain  : 이 한 번의 크기 (사건의 세기)
  // rate  : 재생 속도 = 음정. 같은 소리를 조금씩 다르게 내는 데 쓴다.
  // pan   : -1(왼쪽) ~ 1(오른쪽). 화면에서 벌어진 자리를 그대로 쓴다.
  // gap   : 이 소리만의 억제 창. **30ms 아래로는 못 내려간다** — 벨트 반사처럼
  //         판마다 수십 번 울리는 것을 더 넓게 잡는 데만 쓴다.
  play(key, { gain = 1, rate = 1, pan = 0, vary = 0.03, priority = 0, gap = 0 } = {}) {
    const e = this.engine
    if (!e.ready || e.muted || e.hidden) return null
    const ctx = this.ctx
    const now = ctx.currentTime
    // ① 같은 소리 30ms 억제 (종류에 따라 더 길게)
    const last = this.last.get(key)
    if (last !== undefined && now - last < Math.max(DEDUP, gap)) return null
    // ② 보이스 상한. 넘치면 급하지 않은 것부터 버린다.
    if (this.voices >= MAX_VOICES && priority <= 0) return null
    const buf = this.ensure(key)
    if (!buf) return null
    this.last.set(key, now)

    const src = ctx.createBufferSource()
    src.buffer = buf
    // 같은 소리가 연달아 날 때 완전히 같으면 기계로 들린다. 재생 속도를
    // 조금씩 흔들면 같은 버퍼로도 매번 다른 소리가 된다(캐시를 지키면서).
    src.playbackRate.value = Math.max(0.25, rate * (1 + (Math.random() * 2 - 1) * vary))

    // 게인은 언제나 램프로 움직인다(최소 5ms). 다만 그 5ms를 **소리가 시작하기
    // 전에** 태운다 — 소리 위에 겹치면 당구공 소리(18ms)처럼 짧은 것은
    // 어택의 3분의 1이 페이드로 뭉개져서 "딱"이 "툭"이 된다.
    // 5ms 늦게 나가는 것은 아무도 못 알아채고, 게인은 규약대로 램프다.
    const start = now + MIN_RAMP
    const g = ctx.createGain()
    g.gain.setValueAtTime(EXP_FLOOR, now)
    g.gain.linearRampToValueAtTime(Math.max(EXP_FLOOR, gain), start)

    let tail = g
    if (pan) {
      const p = ctx.createStereoPanner()
      p.pan.value = Math.max(-1, Math.min(1, pan))
      g.connect(p)
      tail = p
    }
    src.connect(g)
    tail.connect(this.engine.sfxBus)

    this.voices++
    src.onended = () => {
      this.voices--
      try { src.disconnect(); g.disconnect(); if (tail !== g) tail.disconnect() } catch { /* 이미 끊김 */ }
    }
    src.start(start)
    return src
  }

  // ── 오실레이터 보이스 ──
  // 버퍼로 못 만드는 것: 길이가 그때그때 정해지는 글라이드. 레이저 충전이
  // 그렇다 — 판 배속에 따라 실제 길이가 달라진다.
  // **매번 새로 만들고 onended에서 끊는다.** 웹오디오 오실레이터는 재사용이
  // 안 되는 물건이고, 안 끊으면 그래프에 시체가 쌓인다.
  osc({ type = 'sine', f0 = 440, f1 = null, dur = 0.3, gain = 0.3, pan = 0, cutoff = 0, q = 1 } = {}) {
    const e = this.engine
    if (!e.ready || e.muted || e.hidden) return null
    if (this.voices >= MAX_VOICES) return null
    const ctx = this.ctx, now = ctx.currentTime
    const o = ctx.createOscillator()
    o.type = type
    o.frequency.setValueAtTime(Math.max(1, f0), now)
    if (f1 && f1 !== f0) {
      // 주파수도 지수로 민다 — 음정은 로그로 들린다. 하한 규칙은 게인과 같다.
      o.frequency.exponentialRampToValueAtTime(Math.max(EXP_FLOOR, f1), now + Math.max(MIN_RAMP, dur))
    }
    const g = ctx.createGain()
    g.gain.setValueAtTime(EXP_FLOOR, now)
    g.gain.linearRampToValueAtTime(gain, now + Math.max(MIN_RAMP, Math.min(0.04, dur * 0.25)))
    g.gain.exponentialRampToValueAtTime(EXP_FLOOR, now + Math.max(MIN_RAMP * 2, dur))

    let head = o, tail = g
    if (cutoff) {
      const f = ctx.createBiquadFilter()
      f.type = 'lowpass'; f.frequency.value = cutoff; f.Q.value = q
      head.connect(f); f.connect(g); head = f
    } else o.connect(g)
    if (pan) {
      const p = ctx.createStereoPanner()
      p.pan.value = Math.max(-1, Math.min(1, pan))
      g.connect(p); tail = p
    }
    tail.connect(this.engine.sfxBus)

    this.voices++
    o.onended = () => {
      this.voices--
      try { o.disconnect(); g.disconnect(); if (head !== o) head.disconnect(); if (tail !== g) tail.disconnect() } catch { /* 이미 끊김 */ }
    }
    o.start(now)
    o.stop(now + Math.max(MIN_RAMP * 3, dur) + 0.02)
    return o
  }

  // ── 잡음 보이스 ──
  // 교신 치지직 · 분사처럼 "길이와 색을 그때 정하는" 잡음. 대역폭을 좁히면
  // 무전기, 넓히면 로켓이다. 여기도 매번 새로 만들고 onended에서 끊는다.
  noise({ dur = 0.2, gain = 0.25, pan = 0, band = 1400, q = 0.9, sweep = 0 } = {}) {
    const e = this.engine
    if (!e.ready || e.muted || e.hidden) return null
    if (this.voices >= MAX_VOICES) return null
    const buf = this.ensureNoise()
    if (!buf) return null
    const ctx = this.ctx, now = ctx.currentTime
    const src = ctx.createBufferSource()
    src.buffer = buf
    src.loop = true
    // 1초짜리 잡음을 매번 같은 자리에서 재생하면 같은 "찌직"이 반복된다.
    const start = Math.random() * 0.8

    const f = ctx.createBiquadFilter()
    f.type = 'bandpass'
    f.frequency.setValueAtTime(Math.max(40, band), now)
    if (sweep) f.frequency.exponentialRampToValueAtTime(Math.max(40, band * sweep), now + Math.max(MIN_RAMP, dur))
    f.Q.value = q

    const g = ctx.createGain()
    g.gain.setValueAtTime(EXP_FLOOR, now)
    g.gain.linearRampToValueAtTime(gain, now + Math.max(MIN_RAMP, Math.min(0.03, dur * 0.2)))
    g.gain.exponentialRampToValueAtTime(EXP_FLOOR, now + Math.max(MIN_RAMP * 2, dur))

    let tail = g
    src.connect(f); f.connect(g)
    if (pan) {
      const p = ctx.createStereoPanner()
      p.pan.value = Math.max(-1, Math.min(1, pan))
      g.connect(p); tail = p
    }
    tail.connect(this.engine.sfxBus)

    this.voices++
    src.onended = () => {
      this.voices--
      try { src.disconnect(); f.disconnect(); g.disconnect(); if (tail !== g) tail.disconnect() } catch { /* 이미 끊김 */ }
    }
    src.start(now, start)
    src.stop(now + Math.max(MIN_RAMP * 3, dur) + 0.02)
    return src
  }
}
