// T1-9. 질량은 그대로 두고 반지름만 R_SCALE배 — 밀도가 낮아지는 것이지
// 무거워지는 게 아니다(중력·Δv·무게등급은 전부 μ만 본다).
export const radiusOf = (mu) => 1.6 * R_SCALE * Math.cbrt(mu)
// 반지름 하나로 판정 원을 구한다. **아직 천체가 아닌 것**도 물어야 하기
// 때문에 따로 뺐다 — 궤도 자리를 찾는 쪽(system.freeOrbit)은 "이만한 반지름의
// 공을 여기 놓아도 되는가"를 묻는데, 예전에는 거기서 radius × HIT_R 로 직접
// 계산해 **MIN_HIT_R 바닥값을 빼먹었다.** 소행성급(반지름 3~5)은 실제 판정
// 원이 23.4인데 10~17로 쳐서 자리를 잡았고, 그만큼 이웃에 붙었다.
export const hitRadiusFor = (radius) => Math.max(CFG.MIN_HIT_R, radius * CFG.HIT_R)
// 미사일 명중 반경 — 물리(행성끼리 충돌)는 여전히 b.radius를 쓴다.
// 이 함수는 "미사일이 무엇에 맞는가"에만 쓰이고, 렌더도 같은 값을 그린다.
export const hitRadiusOf = (b) =>
  b.type === 'debris' ? b.radius : hitRadiusFor(b.radius)
// 행성끼리는 "보이는 공"이 닿는 순간 터진다 — 판정과 그림이 같은 원이라
// "닿았는데 안 터졌다"가 원천적으로 없다.
export const contactDist = (a, b) => hitRadiusOf(a) + hitRadiusOf(b)
// 성계 반경 — 공을 열댓 개 깔려면 판이 그만큼 넓어야 한다. 다만 무한정
// 넓힐 수는 없다: 미사일이 TTL 안에 반대편까지 닿아야 판이 성립한다
// (LAUNCH_MAX × MISSILE_TTL ≈ 2900 GU 가 실질 사거리 상한).
//
// 예전 식은 1700 + 130 × min(안테, 6)이라 **16판**에야 최대치(2480)에 닿았다.
// 눈금이 스테이지로 바뀌면 같은 식이 6판 만에 끝까지 가 버리므로 — 마릿수는
// 아직 4기인데 판만 최대 크기가 된다 — 기울기를 130에서 80으로 낮춰
// STAGE_CAP(10판)에 맞춰 다시 폈다. 끝값 2500은 예전 2480과 사실상 같고,
// 1판(1780)도 예전 1830에서 거의 안 움직인다. 달라지는 것은 중간뿐이다.
export const aMaxOf = (stage) => 1700 + 80 * Math.min(stage, CFG.STAGE_CAP)   // §7.2
// 카이퍼 벨트 반경 — 성계의 쿠션. 최외곽 궤도(0.95 aMax)의 원점 거리보다
// 넉넉히 밖에 둬서 평시 공전이 벨트를 긁지 않게 한다.
export const beltRadius = (aMax) => aMax * CFG.BELT_MUL

// ─── 판의 두 벽 ─────────────────────────────────────────────────
// 궤도를 놓는 쪽이 둘(stage.buildSolarSystem · system.freeOrbit)인데 둘 다 같은
// 질문을 한다: "이 장반경이 태양에 안 빨려드나 / 벨트 밖으로 안 나가나."
// 답이 갈리면 한쪽에서 만든 궤도를 다른 쪽이 못 믿게 되므로 식을 하나로 둔다.
//
// **장반경이 아니라 근점·원점으로 잰다.** 이심률이 0.13까지 붙는데 장반경만
// 보면 근점이 코로나 안으로 들어간 궤도를 통과시킨다(예전 stage.js가 그랬다).
// e = 그 궤도에 실릴 수 있는 최대 이심률.
export const aFloorFor = (e) => Math.max(CFG.A_MIN, CFG.R_STAR * 1.6 / (1 - e))
export const aCeilFor = (aMax, e) => (beltRadius(aMax) - CFG.BELT_THICK) / (1 + e)
// 미사일이 느끼는 탈출속도 — 미사일 중력장은 행성 μ를 κ배로 증폭해서 받는다
// (physics.fieldAccel). 그래서 "이 속도로 쏘면 저 천체를 벗어나는가"는
// 진짜 물리가 아니라 이 식으로 물어야 한다. 지구 발사 하한(LAUNCH_MIN)의 근거.
export const escapeSpeed = (mu, d) => Math.sqrt(2 * CFG.KAPPA * mu / Math.max(1, d))
